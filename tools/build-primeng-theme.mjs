// Builds src/scss/primeng/trips-staff-theme.css from PrimeNG's lara-light-blue theme by swapping its palette for the
// TRIPS Staff tokens (src/scss/trips-staff/_tokens.scss). Run after a PrimeNG upgrade: node tools/build-primeng-theme.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'node_modules/primeng/resources/themes/lara-light-blue/theme.css');
const target = resolve(root, 'src/scss/primeng/trips-staff-theme.css');

// Lara colour (lower case) -> Staff colour. Order matters only for readability; every key is a whole hex value.
const palette = {
  // primary blue -> aviation navy
  '#3b82f6': '#12203a',
  '#2563eb': '#0b1527',
  '#1d4ed8': '#0b1527',
  '#bfdbfe': '#c9d2e1',
  '#eff6ff': '#e7ecf5',
  // text
  '#4b5563': '#344054',
  '#6b7280': '#667085',
  '#374151': '#344054',
  '#1f2937': '#101828',
  '#9ca3af': '#98a2b3',
  '#64748b': '#667085',
  // surfaces and lines
  '#f9fafb': '#f8f5f0',
  '#f3f4f6': '#efeae2',
  '#e5e7eb': '#e4ded4',
  '#d1d5db': '#d0d5dd',
  '#dfe7ef': '#e4ded4',
  '#f6f9fc': '#efeae2',
  // states
  '#e24c4c': '#d92d20',
  '#ef4444': '#d92d20',
  '#22c55e': '#12b76a',
  '#1ea97c': '#146c3e',
  '#f97316': '#f28c0f',
  '#cc8925': '#b54708',
  '#0ea5e9': '#175cd3',
};

let css = readFileSync(source, 'utf8');

// Our fonts are set in _theme.scss; drop Lara's Inter faces and root font settings.
css = css.replace(/@font-face\s*{[^}]*}\s*/g, '');
css = css.replace(/^\s*font-family: "Inter var", sans-serif;\n/m, '');
css = css.replace(/^\s*font-feature-settings: "cv02", "cv03", "cv04", "cv11";\n/m, '');
css = css.replace(/^\s*font-variation-settings: normal;\n/m, '');
css = css.replace('--font-family: "Inter var", sans-serif;', '--font-family: var(--ts-font);');

css = css.replace(/#[0-9a-fA-F]{6}\b/g, (hex) => palette[hex.toLowerCase()] ?? hex);
// Translucent primary (focus halos, hover tints)
css = css.replace(/rgba\(59, 130, 246,/g, 'rgba(18, 32, 58,');
css = css.replace('--border-radius: 6px;', '--border-radius: 12px;');

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `/* Generated by tools/build-primeng-theme.mjs from lara-light-blue. Do not edit by hand. */\n${css}`);
console.log(`wrote ${target}`);
